/**
 * Deterministically retrieves today's quote based on day of year
 */
export function getDailyArabicQuote(): ArabicQuote {
  const now = new Date();
  const dayOfYear = Math.floor(
    (now.getTime() - new Date(now.getFullYear(), 0, 0).getTime()) / (1000 * 60 * 60 * 24)
  );
  return CLASSICAL_ARABIC_QUOTES[dayOfYear % CLASSICAL_ARABIC_QUOTES.length];
}
